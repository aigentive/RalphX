const PR_NUMBER: i64 = 77;

fn pr_detail(title: &str, body: Option<&str>) -> PrDetail {
    PrDetail {
        number: PR_NUMBER,
        title: title.to_string(),
        body: body.map(str::to_string),
        author: Some("ralphx".to_string()),
        created_at: None,
        url: Some("https://github.test/pr/77".to_string()),
        state: PrStatus::Open,
        is_draft: false,
        head_ref_name: "feature/metadata".to_string(),
        base_ref_name: "main".to_string(),
    }
}

fn conversation_and_snapshot() -> (ChatConversation, ExistingPrMetadataSnapshot) {
    let project_id = ProjectId::from_string("metadata-reconciliation".to_string());
    let mut conversation = ChatConversation::new_project(project_id);
    conversation.title = Some("RX-42: Metadata reconciliation".to_string());
    let body = "## Before\n\n<!-- ralphx:managed-pr-body:start -->\n---\n\n_Generated by [RalphX](https://github.com/aigentive/ralphx.app)_\n<!-- ralphx:managed-pr-body:end -->";
    (
        conversation,
        ExistingPrMetadataSnapshot::from_detail(pr_detail("Before title", Some(body))),
    )
}

async fn repository_for(
    conversation: &ChatConversation,
) -> Arc<dyn AgentConversationWorkspaceRepository> {
    let repository = Arc::new(MemoryAgentConversationWorkspaceRepository::new());
    let mut workspace = AgentConversationWorkspace::new(
        conversation.id.clone(),
        ProjectId::from_string(conversation.context_id.clone()),
        AgentConversationWorkspaceMode::Edit,
        IdeationAnalysisBaseRefKind::ProjectDefault,
        "main".to_string(),
        Some("main".to_string()),
        Some("0".repeat(40)),
        "feature/metadata".to_string(),
        "/tmp/metadata-reconciliation".to_string(),
    );
    workspace.publication_pr_number = Some(PR_NUMBER);
    workspace.publication_pr_url = Some("https://github.test/pr/77".to_string());
    workspace.publication_pr_status = Some("open".to_string());
    repository.create_or_update(workspace).await.unwrap();
    repository
}

fn patch_decision() -> AgentWorkspacePrMetadataDecision {
    AgentWorkspacePrMetadataDecision::patch(
        Some("Updated title".to_string()),
        Some("## Updated body".to_string()),
    )
    .unwrap()
}

#[tokio::test]
async fn prepare_persists_exact_hash_evidence_and_recomposed_patch() {
    let (conversation, snapshot) = conversation_and_snapshot();
    let repository = repository_for(&conversation).await;
    let github: Arc<dyn GithubServiceTrait> = Arc::new(MockGithubService::new());
    let service = AgentWorkspacePrMetadataReconciliationService::new(&repository, &github)
        .with_plan_markdown("## Plan".to_string());

    let prepared = service
        .prepare(&conversation, &snapshot, &patch_decision())
        .await
        .unwrap();

    assert_eq!(prepared.patch.target_pr_number, PR_NUMBER);
    assert_eq!(
        prepared.patch.requested_title.as_deref(),
        Some("RX-42: Updated title")
    );
    assert!(prepared
        .patch
        .requested_body
        .as_deref()
        .unwrap()
        .starts_with("## Updated body"));
    assert_eq!(prepared.receipt.before_title_sha256, sha256("Before title"));
    assert_eq!(
        prepared.receipt.intended_title_sha256.as_deref().unwrap(),
        sha256("RX-42: Updated title")
    );
    assert_eq!(
        prepared
            .receipt
            .intended_editable_body_sha256
            .as_deref()
            .unwrap(),
        sha256("## Updated body")
    );
    assert_eq!(
        repository
            .get_publication_metadata_receipt(&conversation.id)
            .await
            .unwrap(),
        Some(prepared.receipt)
    );
}

#[tokio::test]
async fn execute_success_mutates_once_and_settles_applied() {
    let (conversation, snapshot) = conversation_and_snapshot();
    let repository = repository_for(&conversation).await;
    let github = Arc::new(MockGithubService::new());
    let github_trait: Arc<dyn GithubServiceTrait> = github.clone();
    let service = AgentWorkspacePrMetadataReconciliationService::new(&repository, &github_trait);
    let prepared = service
        .prepare(&conversation, &snapshot, &patch_decision())
        .await
        .unwrap();
    let worktree = tempfile::tempdir().unwrap();

    assert_eq!(
        service
            .execute(worktree.path(), &conversation.id, &prepared)
            .await
            .unwrap(),
        AgentWorkspacePrMetadataReconciliationOutcome::Applied
    );
    assert_eq!(github.state().patch_pr_metadata_calls, 1);
    let receipt = repository
        .get_publication_metadata_receipt(&conversation.id)
        .await
        .unwrap()
        .unwrap();
    assert_eq!(
        receipt.phase,
        AgentWorkspacePublicationMetadataPhase::Settled
    );
    assert_eq!(
        receipt.state,
        AgentWorkspacePublicationMetadataState::Applied
    );
    let workspace = repository
        .get_by_conversation_id(&conversation.id)
        .await
        .unwrap()
        .unwrap();
    assert_eq!(
        workspace.publication_pr_url.as_deref(),
        Some("https://github.test/pr/77")
    );
    assert_eq!(workspace.publication_pr_status.as_deref(), Some("open"));
    assert_eq!(workspace.publication_push_status.as_deref(), Some("pushed"));
}

