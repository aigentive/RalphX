#[tokio::test]
async fn readback_rejects_concurrent_drift_in_an_unrequested_editable_field() {
    let (conversation, snapshot) = conversation_and_snapshot();
    let repository = repository_for(&conversation).await;
    let github: Arc<dyn GithubServiceTrait> = Arc::new(MockGithubService::new());
    let service = AgentWorkspacePrMetadataReconciliationService::new(&repository, &github);

    let title_only = service
        .prepare(
            &conversation,
            &snapshot,
            &AgentWorkspacePrMetadataDecision::patch(Some("Updated title".to_string()), None)
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(
        classify_readback(
            &title_only.receipt,
            &pr_detail(
                title_only.patch.requested_title.as_deref().unwrap(),
                Some("Concurrent editable body")
            )
        ),
        AgentWorkspacePrMetadataReadbackClassification::Conflicted
    );

    let second_conversation = {
        let mut value = conversation.clone();
        value.id = crate::domain::entities::ChatConversationId::new();
        value
    };
    let second_repository = repository_for(&second_conversation).await;
    let second_service =
        AgentWorkspacePrMetadataReconciliationService::new(&second_repository, &github);
    let body_only = second_service
        .prepare(
            &second_conversation,
            &snapshot,
            &AgentWorkspacePrMetadataDecision::patch(None, Some("## Updated body".to_string()))
                .unwrap(),
        )
        .await
        .unwrap();
    assert_eq!(
        classify_readback(
            &body_only.receipt,
            &pr_detail(
                "Concurrent title",
                body_only.patch.requested_body.as_deref()
            )
        ),
        AgentWorkspacePrMetadataReadbackClassification::Conflicted
    );
}

