#[tokio::test]
async fn one_redraft_refresh_rebinds_authority_and_stale_refresh_has_no_side_effects() {
    let (conversation, snapshot) = conversation_and_snapshot();
    let repository = repository_for(&conversation).await;
    let github = Arc::new(MockGithubService::new());
    let github_trait: Arc<dyn GithubServiceTrait> = github.clone();
    let service = AgentWorkspacePrMetadataReconciliationService::new(&repository, &github_trait);
    let prepared = service
        .prepare(&conversation, &snapshot, &patch_decision())
        .await
        .unwrap();
    let refreshed_snapshot = ExistingPrMetadataSnapshot::from_detail(pr_detail(
        "Concurrent title",
        Some(
            "## Concurrent body\n\n<!-- ralphx:managed-pr-body:start -->\n---\n\n_Generated by [RalphX](https://github.com/aigentive/ralphx.app)_\n<!-- ralphx:managed-pr-body:end -->",
        ),
    ));
    let refreshed_decision = AgentWorkspacePrMetadataDecision::patch(
        Some("Redrafted title".to_string()),
        Some("## Redrafted body".to_string()),
    )
    .unwrap();

    let refreshed = service
        .refresh_prepared(
            &conversation,
            &refreshed_snapshot,
            &refreshed_decision,
            &prepared,
        )
        .await
        .unwrap()
        .expect("current prepared attempt should refresh");
    assert_eq!(refreshed.receipt.attempt_id, prepared.receipt.attempt_id);
    assert_ne!(
        refreshed.receipt.before_authority_sha256,
        prepared.receipt.before_authority_sha256
    );
    assert_eq!(
        repository
            .get_publication_metadata_receipt(&conversation.id)
            .await
            .unwrap(),
        Some(refreshed.receipt.clone())
    );
    assert_eq!(
        repository
            .get_pr_metadata_decision(&conversation.id)
            .await
            .unwrap(),
        Some(refreshed.patch.normalized_decision.clone())
    );

    let worktree = tempfile::tempdir().unwrap();
    assert_eq!(
        service
            .execute(worktree.path(), &conversation.id, &refreshed)
            .await
            .unwrap(),
        AgentWorkspacePrMetadataReconciliationOutcome::Applied
    );
    let receipt_before_stale_refresh = repository
        .get_publication_metadata_receipt(&conversation.id)
        .await
        .unwrap();
    let events_before_stale_refresh = repository
        .list_publication_events(&conversation.id)
        .await
        .unwrap();
    assert!(service
        .refresh_prepared(
            &conversation,
            &refreshed_snapshot,
            &refreshed_decision,
            &prepared,
        )
        .await
        .unwrap()
        .is_none());
    assert_eq!(
        repository
            .get_publication_metadata_receipt(&conversation.id)
            .await
            .unwrap(),
        receipt_before_stale_refresh
    );
    assert_eq!(
        repository
            .list_publication_events(&conversation.id)
            .await
            .unwrap(),
        events_before_stale_refresh
    );
    assert_eq!(github.state().patch_pr_metadata_calls, 1);
}
